export type Dictionary = (typeof dictionaries)[Locale];

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}

export function tName(
  locale: Locale,
  item: { name_en: string; name_ml: string },
): string {
  return locale === "ml" ? item.name_ml : item.name_en;
}

export function tTitle(
  locale: Locale,
  item: { title_en: string; title_ml: string },
): string {
  return locale === "ml" ? item.title_ml : item.title_en;
}

export function tCaption(
  locale: Locale,
  item: { caption_en?: string | null; caption_ml?: string | null },
): string {
  return (locale === "ml" ? item.caption_ml : item.caption_en) ?? "";
}

export function statusLabel(locale: Locale, status: string): string {
  const d = getDictionary(locale);
  const map: Record<string, string> = {
    live: d.live,
    upcoming: d.upcoming,
    completed: d.completed,
    delayed: d.delayed,
    cancelled: d.cancelled,
    next: d.next,
    draft: d.draft,
    entered: d.entered,
    verified: d.verified,
    published: d.published,
  };
  return map[status] ?? status;
}
